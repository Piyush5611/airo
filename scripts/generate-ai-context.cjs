#!/usr/bin/env node
'use strict';

// Regenerates .ai/FILE_STRUCTURE.md only. Other .ai files are hand-written and never touched.
// Uses Node.js built-in modules only so it runs on Windows and Linux without installs.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT_DIR = path.join(ROOT, '.ai');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'FILE_STRUCTURE.md');

const IGNORED_DIRS = new Set([
  'node_modules', '.git', 'dist', 'build', 'out', 'coverage', '.cache', 'cache',
  '.vite', '.next', '.nuxt', '.svelte-kit', '.turbo', '.parcel-cache', '.output',
  '.shots', '.idea', '.vscode', '.cursor', 'tmp', 'temp', '__pycache__'
]);

const IGNORED_FILES = new Set(['.DS_Store', 'Thumbs.db']);
const IGNORED_EXTENSIONS = new Set(['.log', '.map']);

function ignored(name, isDir) {
  if (isDir) return IGNORED_DIRS.has(name);
  if (IGNORED_FILES.has(name)) return true;
  return IGNORED_EXTENSIONS.has(path.extname(name).toLowerCase());
}

function readEntries(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .filter((entry) => !entry.isSymbolicLink())
    .filter((entry) => !ignored(entry.name, entry.isDirectory()))
    .sort((a, b) => {
      if (a.isDirectory() !== b.isDirectory()) return a.isDirectory() ? -1 : 1;
      return a.name.localeCompare(b.name, 'en', { sensitivity: 'base' });
    });
}

const stats = { dirs: 0, files: 0 };

function walk(dir, prefix, lines) {
  const entries = readEntries(dir);
  entries.forEach((entry, index) => {
    const last = index === entries.length - 1;
    const branch = last ? '└── ' : '├── ';
    if (entry.isDirectory()) {
      stats.dirs += 1;
      lines.push(`${prefix}${branch}${entry.name}/`);
      walk(path.join(dir, entry.name), `${prefix}${last ? '    ' : '│   '}`, lines);
    } else {
      stats.files += 1;
      lines.push(`${prefix}${branch}${entry.name}`);
    }
  });
}

function main() {
  const lines = [`${path.basename(ROOT)}/`];
  walk(ROOT, '', lines);
  const body = [
    '# File Structure',
    '',
    '> Generated by `scripts/generate-ai-context.cjs` (`npm run ai:context`). Do not edit by hand.',
    '',
    `Ignored directories: ${Array.from(IGNORED_DIRS).sort().join(', ')}.`,
    'File names are listed only. File contents (including any `.env`) are never read.',
    '',
    `Directories: ${stats.dirs}. Files: ${stats.files}.`,
    '',
    '```text',
    ...lines,
    '```',
    ''
  ].join('\n');
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, body, 'utf8');
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_FILE)} (${stats.dirs} directories, ${stats.files} files).`);
}

main();
